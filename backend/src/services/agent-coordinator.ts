export interface AgentResult {
  success: boolean;
  output: Record<string, any>;
  confidence: number;
  costEstimate: number;
  costActual: number;
  validation: Record<string, any>;
  agent: string;
  raw?: Record<string, any>;
  error?: string;
}

export interface CoordinatorOutcome {
  result: AgentResult;
  trace: AgentResult[];
  mode: string;
  budgetConsumed: number;
  budgetRemaining: number;
  fallbackUsed: boolean;
}

export interface AgentRequest {
  task: string;
  context: Record<string, any>;
}

export class AgentExecutionError extends Error {
  code: string;
  status: number;
  metadata: Record<string, any>;

  constructor(message: string, code: string = 'AGENT-500', status: number = 500, metadata: Record<string, any> = {}) {
    super(message);
    this.name = 'AgentExecutionError';
    this.code = code;
    this.status = status;
    this.metadata = metadata;
  }
}

abstract class AgentAdapter {
  name: string = 'base';
  defaultCostEstimate: number = 0.05;
  env: Record<string, any>;

  constructor(env: Record<string, any>) {
    this.env = env;
  }

  estimateCost(request: AgentRequest): number {
    return this.defaultCostEstimate;
  }

  abstract run(request: AgentRequest, remainingBudget: number, metadata: Record<string, any>): Promise<AgentResult>;
}

